#!/usr/bin/env bash
# Builds a disposable sandbox image with Charm Crush inside, installs a
# launcher named `crush-sandbox` and points an alias (default: `crush`) at it.
#
# The launcher bind-mounts:
#   * the current directory   -> /workspace   (read/write, Crush's workdir)
#   * ~/.config/crush         -> global config (crushrc, crush.json, themes)
#   * ~/.local/share/crush    -> global data   (sessions, provider auth)
#
# Usage:
#   ./install.sh [options]
#
# Options:
#   --version <x.y.z>   Crush release to install (default: Dockerfile ARG)
#   --image <name>      Image repository name (default: crush-sandbox)
#   --alias <name>      Alias to install (default: crush)
#   --shell <name>      bash | zsh | fish | all | none (default: current shell)
#   --no-build          Install the launcher and alias, skip the image build
#   --no-alias          Do not touch any shell rc file
#   --build-only        Build the image only, do not install anything
#   -h, --help          Show this help
#
# Environment:
#   CRUSH_SANDBOX_DOCKER   Container CLI to use (e.g. "sudo docker", "podman")
#   CRUSH_SANDBOX_BIN_DIR  Where to put the launcher (default: ~/.local/bin)
#   CRUSH_SANDBOX_ALIAS    Same as --alias
#   CRUSH_SANDBOX_REBUILD  Set to 1 to force a rebuild on next launch

set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
DOCKERFILE="$SCRIPT_DIR/Dockerfile"

die() {
    printf 'error: %s\n' "$*" >&2
    exit 1
}

usage() {
    awk 'NR == 1 { next } /^#/ { sub(/^# ?/, ""); print; next } { exit }' "${BASH_SOURCE[0]}"
}

[ -f "$DOCKERFILE" ] || die "Dockerfile not found next to install.sh ($DOCKERFILE)"

DEFAULT_VERSION="$(sed -n 's/^ARG CRUSH_VERSION=//p' "$DOCKERFILE" | head -n 1)"
CRUSH_VERSION="${CRUSH_VERSION:-${DEFAULT_VERSION:-0.100.0}}"
IMAGE_REPO="${CRUSH_SANDBOX_IMAGE_REPO:-crush-sandbox}"
ALIAS_NAME="${CRUSH_SANDBOX_ALIAS:-crush}"
INSTALL_DIR="${CRUSH_SANDBOX_BIN_DIR:-${XDG_BIN_HOME:-$HOME/.local/bin}}"
WRAPPER="$INSTALL_DIR/crush-sandbox"
SHELLS="auto"
DO_BUILD=1
DO_ALIAS=1

while [ $# -gt 0 ]; do
    case "$1" in
        --version)   [ $# -ge 2 ] || die "--version needs a value"; CRUSH_VERSION="$2"; shift 2 ;;
        --version=*) CRUSH_VERSION="${1#*=}"; shift ;;
        --image)     [ $# -ge 2 ] || die "--image needs a value"; IMAGE_REPO="$2"; shift 2 ;;
        --image=*)   IMAGE_REPO="${1#*=}"; shift ;;
        --alias)     [ $# -ge 2 ] || die "--alias needs a value"; ALIAS_NAME="$2"; shift 2 ;;
        --alias=*)   ALIAS_NAME="${1#*=}"; shift ;;
        --shell)     [ $# -ge 2 ] || die "--shell needs a value"; SHELLS="$2"; shift 2 ;;
        --shell=*)   SHELLS="${1#*=}"; shift ;;
        --no-build)  DO_BUILD=0; shift ;;
        --no-alias)  DO_ALIAS=0; shift ;;
        --build-only) DO_BUILD=1; DO_ALIAS=0; shift ;;
        -h|--help)   usage; exit 0 ;;
        *) die "unknown option: $1 (try --help)" ;;
    esac
done

[ -n "$ALIAS_NAME" ] || die "alias name must not be empty"
[ -n "$IMAGE_REPO" ] || die "image name must not be empty"
case "$SHELLS" in
    auto|bash|zsh|fish|all|none) ;;
    *) die "--shell must be one of: auto, bash, zsh, fish, all, none" ;;
esac

IMAGE="${IMAGE_REPO}:${CRUSH_VERSION}"

sed_escape() {
    printf '%s' "$1" | sed -e 's/[\\|&]/\\&/g'
}

mkdir -p "$INSTALL_DIR"

# ---------------------------------------------------------------------------
# Launcher
# ---------------------------------------------------------------------------

WRAPPER_TMP="$(mktemp)"
cat > "$WRAPPER_TMP" <<'WRAPPER_EOF'
#!/usr/bin/env bash
# Launcher generated by install.sh. Runs Charm Crush in a disposable container
# with the current directory as the workdir and the host config mounted.
#
# Overridable at run time:
#   CRUSH_SANDBOX_DOCKER    container CLI (default: docker)
#   CRUSH_SANDBOX_IMAGE     image to run (default: @IMAGE@)
#   CRUSH_SANDBOX_CONTEXT   build context used for on-demand builds
#   CRUSH_SANDBOX_REBUILD=1 force a rebuild before running

set -euo pipefail

IMAGE="${CRUSH_SANDBOX_IMAGE:-@IMAGE@}"
VERSION="${CRUSH_SANDBOX_VERSION:-@VERSION@}"
CONTEXT="${CRUSH_SANDBOX_CONTEXT:-@CONTEXT@}"

IFS=' ' read -r -a DOCKER <<< "${CRUSH_SANDBOX_DOCKER:-docker}"

CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/crush"
DATA_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/crush"
mkdir -p "$CONFIG_DIR" "$DATA_DIR"

build_image() {
    if [ ! -f "$CONTEXT/Dockerfile" ]; then
        printf 'error: build context not found: %s\n' "$CONTEXT" >&2
        printf 'hint: re-run install.sh from the project directory.\n' >&2
        exit 1
    fi
    if ! "${DOCKER[@]}" info >/dev/null 2>&1; then
        printf 'error: cannot reach the container daemon with: %s\n' "${DOCKER[*]}" >&2
        printf 'hint: add your user to the docker group, start rootless docker,\n' >&2
        printf '      or run with CRUSH_SANDBOX_DOCKER="sudo docker".\n' >&2
        exit 1
    fi
    printf 'building %s from %s ...\n' "$IMAGE" "$CONTEXT" >&2
    "${DOCKER[@]}" build \
        --build-arg "CRUSH_VERSION=$VERSION" \
        --build-arg "USER_UID=$(id -u)" \
        --build-arg "USER_GID=$(id -g)" \
        -t "$IMAGE" \
        "$CONTEXT" >&2
}

if [ "${CRUSH_SANDBOX_ACTION:-run}" = "build" ]; then
    build_image
    exit 0
fi

if [ "${CRUSH_SANDBOX_REBUILD:-0}" = "1" ] || ! "${DOCKER[@]}" image inspect "$IMAGE" >/dev/null 2>&1; then
    build_image
fi

TTY_ARGS=()
if [ -t 0 ]; then TTY_ARGS+=(-i); fi
if [ -t 1 ]; then TTY_ARGS+=(-t); fi

MOUNT_ARGS=(
    --mount "type=bind,source=$PWD,target=/workspace"
    --mount "type=bind,source=$CONFIG_DIR,target=/home/crush/.config/crush"
    --mount "type=bind,source=$DATA_DIR,target=/home/crush/.local/share/crush"
)

if [ -f "$HOME/.config/AGENTS.md" ]; then
    MOUNT_ARGS+=(--mount "type=bind,source=$HOME/.config/AGENTS.md,target=/home/crush/.config/AGENTS.md,readonly")
fi
if [ -f "$HOME/.gitconfig" ]; then
    MOUNT_ARGS+=(--mount "type=bind,source=$HOME/.gitconfig,target=/home/crush/.gitconfig,readonly")
fi
if [ -f "${XDG_CONFIG_HOME:-$HOME/.config}/git/config" ]; then
    MOUNT_ARGS+=(--mount "type=bind,source=${XDG_CONFIG_HOME:-$HOME/.config}/git/config,target=/home/crush/.config/git/config,readonly")
fi

ENV_ARGS=(-e TERM)
if [ -n "${SSH_AUTH_SOCK:-}" ] && [ -S "${SSH_AUTH_SOCK}" ]; then
    MOUNT_ARGS+=(--mount "type=bind,source=$SSH_AUTH_SOCK,target=/ssh-agent")
    ENV_ARGS+=(-e "SSH_AUTH_SOCK=/ssh-agent")
fi

PASSTHROUGH_ENV=(
    HYPER_API_KEY
    ANTHROPIC_API_KEY ANTHROPIC_API_ENDPOINT
    OPENAI_API_KEY VERCEL_API_KEY GEMINI_API_KEY ZAI_API_KEY MINIMAX_API_KEY
    SYNTHETIC_API_KEY HF_TOKEN CEREBRAS_API_KEY OPENROUTER_API_KEY
    IONET_API_KEY ALIBABA_SINGAPORE_API_KEY ALIBABA_US_API_KEY GROQ_API_KEY
    AVIAN_API_KEY OPENCODE_API_KEY MOONSHOT_API_KEY XAI_API_KEY
    DEEPSEEK_API_KEY GITHUB_TOKEN GH_TOKEN
    AWS_ACCESS_KEY_ID AWS_SECRET_ACCESS_KEY AWS_SESSION_TOKEN AWS_REGION
    AWS_PROFILE AWS_BEARER_TOKEN_BEDROCK
    AZURE_OPENAI_API_ENDPOINT AZURE_OPENAI_API_KEY AZURE_OPENAI_API_VERSION
    VERTEXAI_PROJECT VERTEXAI_LOCATION
    CATWALK_URL CRUSH_DISABLE_METRICS CRUSH_DISABLE_PROVIDER_AUTO_UPDATE
    DO_NOT_TRACK
    http_proxy https_proxy no_proxy HTTP_PROXY HTTPS_PROXY NO_PROXY
)
for _var in "${PASSTHROUGH_ENV[@]}"; do
    if [ -n "${!_var:-}" ]; then
        ENV_ARGS+=(-e "$_var")
    fi
done

_project="$(basename -- "$PWD")"
_project="$(printf '%s' "$_project" | tr -c 'A-Za-z0-9_.-' '-')"
CONTAINER_NAME="crush-sandbox-${_project:-workspace}-$$"

exec "${DOCKER[@]}" run --rm --init \
    --name "$CONTAINER_NAME" \
    --security-opt no-new-privileges \
    --cap-drop ALL \
    -w /workspace \
    -e HOME=/home/crush \
    -e CRUSH_GLOBAL_CONFIG=/home/crush/.config/crush \
    -e CRUSH_GLOBAL_DATA=/home/crush/.local/share/crush \
    "${TTY_ARGS[@]}" "${ENV_ARGS[@]}" "${MOUNT_ARGS[@]}" \
    "$IMAGE" "$@"
WRAPPER_EOF

sed -e "s|@IMAGE@|$(sed_escape "$IMAGE")|g" \
    -e "s|@VERSION@|$(sed_escape "$CRUSH_VERSION")|g" \
    -e "s|@CONTEXT@|$(sed_escape "$SCRIPT_DIR")|g" \
    "$WRAPPER_TMP" > "$WRAPPER"
rm -f "$WRAPPER_TMP"
chmod 0755 "$WRAPPER"

# ---------------------------------------------------------------------------
# Alias in shell rc files
# ---------------------------------------------------------------------------

install_alias_in() {
    local rc="$1"
    local kind="$2"
    mkdir -p "$(dirname -- "$rc")"
    [ -f "$rc" ] || : > "$rc"

    local tmp
    tmp="$(mktemp)"
    awk '
        /^# >>> crush-sandbox >>>$/ { skip = 1; next }
        /^# <<< crush-sandbox <<<$/ { skip = 0; next }
        !skip
    ' "$rc" > "$tmp"

    {
        printf '\n# >>> crush-sandbox >>>\n'
        if [ "$kind" = fish ]; then
            printf 'alias %s %s\n' "$ALIAS_NAME" "$(printf '%q' "$WRAPPER")"
        else
            printf 'alias %s=%s\n' "$ALIAS_NAME" "$(printf '%q' "$WRAPPER")"
        fi
        printf '# <<< crush-sandbox <<<\n'
    } >> "$tmp"

    cat "$tmp" > "$rc"
    rm -f "$tmp"
    printf 'alias installed in %s\n' "$rc"
}

targets=()
case "$SHELLS" in
    auto)
        case "$(basename -- "${SHELL:-}")" in
            zsh)  targets+=("$HOME/.zshrc") ;;
            fish) targets+=("${XDG_CONFIG_HOME:-$HOME/.config}/fish/config.fish") ;;
            *)    targets+=("$HOME/.bashrc") ;;
        esac
        ;;
    bash) targets+=("$HOME/.bashrc") ;;
    zsh)  targets+=("$HOME/.zshrc") ;;
    fish) targets+=("${XDG_CONFIG_HOME:-$HOME/.config}/fish/config.fish") ;;
    all)
        [ -f "$HOME/.bashrc" ] && targets+=("$HOME/.bashrc")
        [ -f "$HOME/.zshrc" ] && targets+=("$HOME/.zshrc")
        [ -f "${XDG_CONFIG_HOME:-$HOME/.config}/fish/config.fish" ] && targets+=("${XDG_CONFIG_HOME:-$HOME/.config}/fish/config.fish")
        [ "${#targets[@]}" -gt 0 ] || targets+=("$HOME/.bashrc")
        ;;
    none) ;;
esac

if [ "$DO_ALIAS" -eq 1 ]; then
    for rc in "${targets[@]}"; do
        case "$rc" in
            */fish/config.fish) install_alias_in "$rc" fish ;;
            *) install_alias_in "$rc" sh ;;
        esac
    done
fi

# ---------------------------------------------------------------------------
# Build
# ---------------------------------------------------------------------------

if [ "$DO_BUILD" -eq 1 ]; then
    if CRUSH_SANDBOX_ACTION=build CRUSH_SANDBOX_IMAGE="$IMAGE" "$WRAPPER"; then
        printf 'image ready: %s\n' "$IMAGE"
    else
        printf 'warning: image build failed; run "%s" later to retry.\n' "$WRAPPER" >&2
        exit 1
    fi
fi

command -v crush >/dev/null 2>&1 && [ "$ALIAS_NAME" = "crush" ] && \
    printf 'note: an existing crush binary is on PATH; the alias shadows it in interactive shells.\n'

printf '\nDone.\n'
printf '  launcher: %s\n' "$WRAPPER"
[ "$DO_ALIAS" -eq 1 ] && printf '  alias:    %s (open a new shell or source your rc file)\n' "$ALIAS_NAME"
printf '  try:      cd ~/some/project && %s\n' "$ALIAS_NAME"
